#!/usr/bin/env python3
"""Generate compact immutable decoding tables from Python's GB18030 codec."""
from pathlib import Path
out = Path(__file__).resolve().parents[2] / 'components/applications/reader/src/parser/reader_gb18030.inc'
values=[]
for lead in range(0x81,0xff):
    for trail in range(0x40,0xff):
        if trail==0x7f: continue
        try: values.append(ord(bytes((lead,trail)).decode('gb18030')))
        except UnicodeDecodeError: values.append(0xfffd)
ranges=[]
for cp in range(0x110000):
    if 0xd800 <= cp <= 0xdfff: continue
    b=chr(cp).encode('gb18030')
    if len(b)!=4: continue
    pointer=((b[0]-0x81)*10+b[1]-0x30)*1260+(b[2]-0x81)*10+b[3]-0x30
    ranges.append((pointer,cp))
ranges.sort()
segments=[]
for pointer, cp in ranges:
    if segments and pointer == segments[-1][1]+1 and cp == segments[-1][2]+pointer-segments[-1][0]:
        segments[-1][1]=pointer
    else: segments.append([pointer,pointer,cp])
with out.open('w') as f:
    f.write('/* SPDX-License-Identifier: MIT\n * Generated by tools/reader/generate_gb18030.py; do not edit. */\n')
    f.write('static const uint16_t gb_two[] = {\n')
    for i in range(0,len(values),16): f.write('    '+','.join(f'0x{x:04x}' for x in values[i:i+16])+',\n')
    f.write('};\nstatic const struct { uint32_t first, last, codepoint; } gb_four[] = {\n')
    for a,b,c in segments: f.write(f'    {{{a},{b},{c}}},\n')
    f.write('};\n')
print(f'{len(values)} double-byte mappings, {len(segments)} four-byte ranges -> {out}')
